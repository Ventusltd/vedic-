"""Actual pinned nearest ranking, followed by existing ORIENT; PRE-ADMISSION only.
No caller-supplied ranking is trusted: receipt verification reruns exact source.
"""
import argparse, copy, json, math, os, subprocess, sys, tempfile
from pathlib import Path
from tacit_b_composition import load_bond, validate_selected_contract, need, refusal

class Ranking:
    def __init__(self,f,descriptor,source_root):
        self.f=f
        self.pins={}
        self.payload={}
        for item in descriptor["inputs"]:
            role=item["role"]
            if role not in ("module","local_dependency","adapter"):continue
            raw=f.read_file(source_root,item["filename"])
            need(f.digest(raw,item["algorithm"])==item["digest"],"SOURCE_PIN:"+role)
            name="index.mjs" if role=="adapter" else item["filename"]
            self.payload[name]=raw
            self.pins[name]={"repo":item["repo"],"commit":item["commit"],"path":item["path"],"sha256":f.sha(raw),"git_blob":f.digest(raw,"git-blob-sha1")}
        need(set(self.payload)=={"index.mjs","v9-nearest-search.js","v9-geodesy.js"},"SOURCE_CLOSURE")
        self.descriptor_sha=f.sha(f.canonical(descriptor))
    def run(self,request):
        f=self.f
        need(isinstance(request,dict) and set(request)=={"crs","query","records","minimumKv"},"REQUEST_FIELDS")
        raw=f.canonical(request)
        need(len(raw)<=2_000_000,"REQUEST_SIZE")
        with tempfile.TemporaryDirectory(prefix="vedic-nearest-dev-") as tmp:
            root=Path(tmp)
            pkg=root/"node_modules/@ventus-internal/vedic-nearest"
            pkg.mkdir(parents=True)
            for name,data in self.payload.items():(pkg/name).write_bytes(data)
            (pkg/"package.json").write_text('{"name":"@ventus-internal/vedic-nearest","private":true,"type":"module","exports":"./index.mjs"}')
            (root/"input.json").write_bytes(raw)
            (root/"run.mjs").write_text("""import {nearestSubstation} from '@ventus-internal/vedic-nearest';
import {nearestSubstation as direct} from './node_modules/@ventus-internal/vedic-nearest/index.mjs';
import {readFileSync} from 'node:fs';
if(direct!==nearestSubstation) throw Error('import parity');
const request=JSON.parse(readFileSync('input.json','utf8'));
try {const out=nearestSubstation(request); console.log(JSON.stringify({ok:true,result:out}));}
catch(e){console.log(JSON.stringify({ok:false}));}
""")
            out=f.strict(subprocess.check_output(["node","--no-addons","run.mjs"],cwd=root,env={"PATH":os.environ["PATH"]},timeout=20))
        need(out["ok"] is True,"PRODUCER_INPUT_REFUSED")
        result=out["result"]
        selected=None if result is None else next(r["location"] for r in request["records"] if r["id"]==result["id"])
        body={"schema":"tacit-b.nearest-ranking.v1","state":"PRE_ADMISSION_PRODUCER_EXECUTED",
              "request_sha256":f.sha(raw),"request":request,"source_pins":self.pins,
              "descriptor_sha256":self.descriptor_sha,"result":result,"selected_location":selected,
              "threshold_unit":"kV","distance_unit":"km","tie_rule":"exact distance tie preserves caller order",
              "admission":False,"redistribution":"BLOCKED"}
        return {**body,"receipt_sha256":f.sha(f.canonical(body))}
    def replay(self,request,receipt):
        # Rehashing fabricated assertions cannot pass: the full receipt is
        # regenerated by actual pinned source in a clean process.
        actual=self.run(request)
        need(receipt==actual,"RANKING_REPLAY_MISMATCH")
        return actual["result"]

def main():
    p=argparse.ArgumentParser()
    for k in ("factory","nearest","sources","archive","receipt","out"):p.add_argument("--"+k,type=Path,required=True)
    a=p.parse_args()
    sys.path.insert(0,str(a.factory/"tools"))
    import package_factory as f
    import typed_package_execution as t
    d=f.strict((a.factory/"packages/factory/pending/nearest-substation.json").read_bytes())
    need(refusal(lambda:f.admit(d))=="FAMILY_NOT_ADMITTED","ADMISSION_CHANGED")
    rank=Ranking(f,d,a.sources)
    candidate=a.nearest/"packages/nearest-candidate"
    bond=load_bond(candidate/"kuiper_bond.py")
    fixture=f.strict((candidate/"consumer-fixture.json").read_bytes())
    request=fixture["input"]
    raw=a.archive.read_bytes(); receipt=f.strict(a.receipt.read_bytes())
    def orient(points):
        q={"schema":t.SCHEMA,"family":"orient","export":"orient","descriptor_sha256":t.DESCRIPTOR,
           "archive_sha256":t.ARCHIVE,"ports":dict(t.PORTS),"input":points}
        return t.execute(q,raw,receipt)
    def compose(req,ranking):
        result=rank.replay(req,ranking)
        if result is None:return {"state":"NO_ELIGIBLE_RECORD","orient":None}
        points=validate_selected_contract(bond,req,result,bond.sha(bond.canonical(req)),lambda p:orient(p)["pattern"]["output"])
        return {"state":"PRE_ADMISSION_COMPOSITION_EXECUTED","orient":orient(points)}
    ranked=rank.run(request)
    actual=compose(request,ranked)
    need(ranked["result"]["id"]=="eligible","REFERENCE_ID")
    out=actual["orient"]["pattern"]["output"]
    need(abs(out["distance_km"]-111.31949079327356)<=1e-8 and abs(out["initial_bearing_deg"]-90)<=1e-8,"REFERENCE")
    tests={}
    def check(name,ok):
        need(ok,name);tests[name]="PASS"
    def reject(name,fn,reason):
        check(name,refusal(fn)==reason)
    check("repeat",rank.run(request)==ranked and compose(request,ranked)==actual)
    forged=copy.deepcopy(ranked);forged["result"]={"id":"far","distance_km":222.63898158654712};forged["selected_location"]={"longitude":2,"latitude":0}
    def rehash(x):
        x["receipt_sha256"]=f.sha(f.canonical({k:v for k,v in x.items() if k!="receipt_sha256"}));return x
    reject("C_farther_eligible_rehashed",lambda:compose(request,rehash(forged)),"RANKING_REPLAY_MISMATCH")
    forged=copy.deepcopy(ranked);forged["result"]["distance_km"]=0
    reject("forged_distance_rehashed",lambda:compose(request,rehash(forged)),"RANKING_REPLAY_MISMATCH")
    forged=copy.deepcopy(ranked);forged["source_pins"]["index.mjs"]["sha256"]="0"*64
    reject("forged_source_rehashed",lambda:compose(request,rehash(forged)),"RANKING_REPLAY_MISMATCH")
    changed=copy.deepcopy(request);changed["minimumKv"]=275
    reject("changed_threshold_stale_receipt",lambda:compose(changed,ranked),"RANKING_REPLAY_MISMATCH")
    check("new_threshold",rank.run(changed)["result"]["id"]=="far")
    changed=copy.deepcopy(request);changed["records"].reverse()
    reject("permuted_stale_receipt",lambda:compose(changed,ranked),"RANKING_REPLAY_MISMATCH")
    check("permutation_non_tie",rank.run(changed)["result"]["id"]=="eligible")
    def rec(id,lon,volts):
        return {"id":id,"name":id,"location":{"longitude":lon,"latitude":0},"voltages_kv":volts}
    ties={**request,"records":[rec("east",1,[132]),rec("west",-1,[132])]}
    check("tie_first",rank.run(ties)["result"]["id"]=="east")
    check("tie_reversed",rank.run({**ties,"records":list(reversed(ties["records"]))})["result"]["id"]=="west")
    empty={**request,"records":[]}
    check("empty",compose(empty,rank.run(empty))["state"]=="NO_ELIGIBLE_RECORD")
    low={**request,"records":[rec("low",.1,[33]),rec("unknown",.01,[])]}
    check("no_eligible",compose(low,rank.run(low))["orient"] is None)
    check("unknown_voltage_excluded",rank.run({**request,"records":[rec("unknown",.01,[]),rec("known",1,[132])]})["result"]["id"]=="known")
    for name,bad in [("duplicate_id",{**request,"records":request["records"]+[request["records"][0]]}),
                     ("invalid_voltage",{**request,"records":[rec("bad",1,["132"])]}),
                     ("invalid_coordinates",{**request,"query":{"longitude":181,"latitude":0}}),
                     ("wrong_crs",{**request,"crs":"EPSG:27700"}),
                     ("negative_threshold",{**request,"minimumKv":-1})]:
        reject(name,lambda bad=bad:rank.run(bad),"PRODUCER_INPUT_REFUSED")
    report={"schema":"tacit-b.nearest-pre-admission-composition.v1","ranking":ranked,"composition":actual,
            "checks":tests,"factory_admission":"FAMILY_NOT_ADMITTED","semantic_full_instruction":"UNSUPPORTED_INTENT_OR_UNADMITTED_FAMILY",
            "nearest_archive":None,"independent_acceptance":False,"rights":"BLOCKED"}
    a.out.write_bytes(f.canonical(report))
    print(json.dumps({"state":actual["state"],"result":ranked["result"],"orient":out,"checks":len(tests),"sha256":f.sha(a.out.read_bytes())},sort_keys=True))

if __name__=="__main__":main()
